test('only dirty drafts register browser departure protection; immediate preferences stay freely navigable', async ({ page }) => {
  const preventsUnload = () => page.evaluate(() => {
    const event = new Event('beforeunload', { cancelable: true })
    window.dispatchEvent(event)
    return event.defaultPrevented
  })
  expect(await preventsUnload()).toBe(false)
  await openYouDestination(page, 'Preferences')
  await page.getByRole('switch', { name: 'Sound', exact: true }).uncheck()
  expect(await preventsUnload()).toBe(false)
  await openYouDestination(page, 'Profile & goals')
  await page.getByRole('spinbutton', { name: 'Height', exact: true }).fill('181')
  expect(await preventsUnload()).toBe(true)
  await page.getByRole('button', { name: 'Save settings', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Save settings', exact: true })).toHaveCount(0)
  expect(await preventsUnload()).toBe(false)
  await nav(page).getByRole('link', { name: 'Insights' }).click()
  await expect(page).toHaveURL(/\/progress$/)
  await expect(departure(page)).toHaveCount(0)
})

test('intentional sign-out offers Stay or Discard and never promises Save during sign-out', async ({ page }) => {
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill('Pending signout name')
  await draftConnection(page, 'api-key')
  await page.getByRole('textbox', { name: 'API key', exact: true }).fill('pending-dummy-secret')
  await openYouDestination(page, 'Account')
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Sign out with unsaved changes?', exact: true })
  await expect(dialog.getByRole('button', { name: 'Stay', exact: true })).toBeFocused()
  await expect(dialog).toContainText('Stay and Save settings before signing out')
  await expect(dialog.getByRole('button', { name: /Save and/ })).toHaveCount(0)
  await dialog.getByRole('button', { name: 'Stay', exact: true }).click()
  await openYouDestination(page, 'AI setup')
  await expect(page.getByRole('textbox', { name: 'API key', exact: true })).toHaveValue('pending-dummy-secret')
  await openYouDestination(page, 'Account')
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await dialog.getByRole('button', { name: 'Discard and sign out', exact: true }).click()
  await expect(page).toHaveURL(/\/login$/)
  await expect(page.getByRole('textbox', { name: 'API key', exact: true })).toHaveCount(0)
  await expect(page.getByRole('dialog')).toHaveCount(0)
})

test('forced account expiry bypasses a pending prompt and removes secret drafts', async ({ page }) => {
  await draftConnection(page, 'api-key')
  await page.getByRole('textbox', { name: 'API key', exact: true }).fill('pending-expiry-secret')
  await nav(page).getByRole('link', { name: 'Insights' }).click()
  await expect(departure(page)).toBeVisible()
  await page.evaluate(() => {
    localStorage.removeItem('fud-ai-auth-session')
    window.dispatchEvent(new StorageEvent('storage', { key: 'fud-ai-auth-session', newValue: null }))
  })
  await expect(page).toHaveURL(/\/login$/)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('textbox', { name: 'API key', exact: true })).toHaveCount(0)
  expect(await page.evaluate(() => Object.values(sessionStorage).some(value => value.includes('pending-expiry-secret')))).toBe(false)
})

