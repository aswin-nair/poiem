import { expect, test, type Page } from '@playwright/test'
import { nav, openYouDestination, signUpAndOnboard } from './helpers'

async function appliedSettings(page: Page) {
  return page.evaluate(async () => {
    const user = JSON.parse(localStorage.getItem('fud-ai-auth-session') ?? 'null') as { sub: string } | null
    if (!user) throw new Error('Expected signed-in account')
    const moduleUrl = '/src/lib/durableState.ts'
    const { loadDurableState } = await import(moduleUrl)
    const saved = await loadDurableState(user.sub)
    if (!saved) throw new Error('Expected device snapshot')
    return saved.state
  })
}

async function draftConnection(page: Page, auth: 'none' | 'api-key' = 'none') {
  await openYouDestination(page, 'AI setup')
  await page.getByRole('switch', { name: 'Use my own API', exact: true }).check()
  await page.getByLabel('API endpoint', { exact: true }).fill('https://custom-ai.example/v1/chat/completions')
  await page.getByLabel('Model', { exact: true }).fill('test-vision')
  await page.locator('.you-api-auth > summary').click()
  await page.getByRole('combobox', { name: 'Authentication method', exact: true }).selectOption(auth)
  await page.locator('.you-api-auth > summary').click()
}

const departure = (page: Page) => page.getByRole('dialog', { name: 'Keep your Settings changes?', exact: true })

test.beforeEach(async ({ page }) => {
  await page.route('**/api/**', route => route.abort('blockedbyclient'))
  await page.route('https://custom-ai.example/**', route => route.abort('blockedbyclient'))
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await signUpAndOnboard(page)
  await page.goto('/settings?panel=profile')
})

test('Stay, Escape and backdrop keep both drafts while panel and search navigation remain free', async ({ page }) => {
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill('Draft name')
  await draftConnection(page)
  await openYouDestination(page, 'Preferences')
  await page.getByRole('switch', { name: 'Sound', exact: true }).uncheck()
  await nav(page).getByRole('link', { name: 'Insights' }).click()
  await expect(departure(page).getByRole('button', { name: 'Stay', exact: true })).toBeFocused()
  await expect(departure(page)).toContainText('Unsaved profile and AI changes')
  await page.keyboard.press('Escape')
  await expect(departure(page)).toBeHidden()
  await nav(page).getByRole('link', { name: 'Insights' }).click()
  await page.locator('.k-sheet-backdrop').click({ position: { x: 5, y: 5 } })
  await expect(departure(page)).toBeHidden()
  await page.getByRole('searchbox', { name: 'Find a setting' }).fill('name')
  await page.getByRole('search', { name: 'Find settings' }).getByRole('link', { name: /^Name/ }).click()
  await expect(page.getByRole('textbox', { name: 'Name', exact: true })).toHaveValue('Draft name')
  await openYouDestination(page, 'AI setup')
  await expect(page.getByLabel('Model', { exact: true })).toHaveValue('test-vision')
  await expect.poll(async () => (await appliedSettings(page)).profile.soundEnabled).toBe(false)
  expect((await appliedSettings(page)).aiSettings.accessMode).toBe('managed')
})

